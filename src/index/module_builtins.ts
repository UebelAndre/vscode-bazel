import { AttrSchema, CallableSchema } from "./rule_schema";

type Param = [name: string, doc: string, mandatory?: boolean];

function builtin(name: string, doc: string, params: Param[]): CallableSchema {
  // `*args` and `**kwargs` are not keywords one can complete; `**kwargs`
  // means any keyword is accepted.
  const attrs: AttrSchema[] = params
    .filter(([param]) => !param.startsWith("*"))
    .map(([param, paramDoc, mandatory]) => ({
      name: param,
      type: "param",
      doc: paramDoc,
      mandatory: mandatory ?? false,
      implicit: false,
    }));
  const openEnded = params.some(([param]) => param.startsWith("**"));
  return { name, kind: "function", doc, file: "", attrs, openEnded };
}

/** Whether a file is a module file, where the builtins below are available. */
export function isModuleFile(file: string): boolean {
  return /(^|[/\\])(MODULE\.bazel|[^/\\]*\.MODULE\.bazel)$/.test(file);
}


import * as path from "path";
import * as vscode from "vscode";

import {
  BzlDefinition,
  CallableSchema,
  IndexManager,
  LabelResolver,
  ResolvedLocation,
  looksLikeLabel,
  parseLabel,
  shortLabel,
} from "../index";
import { offeredAttrs } from "./schema_support";
import { DocumentCache } from "./starlark_definition_provider";
import { loadBinding, nodeAt } from "./document_analysis";

const MAX_DOC_LENGTH = 1500;

/** Hover information for rules, macros, and labels. */
export class StarlarkHoverProvider implements vscode.HoverProvider {
  constructor(
    private readonly manager: IndexManager,
    private readonly resolver: LabelResolver,
    private readonly documents: DocumentCache,
  ) {}

  public async provideHover(
    document: vscode.TextDocument,
    position: vscode.Position,
  ): Promise<vscode.Hover | undefined> {
    const analyzed = this.documents.get(document);
    const node = nodeAt(analyzed, document.offsetAt(position));
    if (!node) {
      return undefined;
    }
    const ctx = await this.resolver.contextFor(document.uri.fsPath);
    if (!ctx) {
      return undefined;
    }
    await ctx.index.ready;

    if (node.kind === "ident") {
      const name = node.ident.name;
      const bound =
        node.load && node.loadSymbol
          ? { load: node.load, symbol: node.loadSymbol }
          : loadBinding(analyzed.module, name);
      const [found] = bound
        ? await this.resolver.resolveLoadedSymbol(
            bound.load.module.value,
            bound.symbol.original,
            ctx,
          )
        : [];
      // Names without a load() may still have a schema: MODULE.bazel
      // builtins and extension proxies.
      const schema = await this.resolver.schemas.schemaFor(
        name,
        document.uri.fsPath,
      );
      if (!found?.definition && !schema) {
        return undefined;
      }
      return new vscode.Hover(
        definitionMarkdown(name, found, schema, ctx.index.root),
        new vscode.Range(
          document.positionAt(node.ident.start),
          document.positionAt(node.ident.end),
        ),
      );
    }

    if (node.load) {
      return undefined;
    }
    const text = node.literal.value;
    if (
      !looksLikeLabel(text) ||
      (!text.startsWith("@") && !text.startsWith("//") && !text.startsWith(":"))
    ) {
      return undefined;
    }
    const label = parseLabel(text, ctx.pkg);
    if (!label) {
      return undefined;
    }
    const locations = await this.resolver.resolveLabel(label, ctx);
    const first = locations[0];
    if (!first) {
      return undefined;
    }
    const md = new vscode.MarkdownString();
    if (first.target) {
      const t = first.target;
      md.appendCodeblock(`${t.kind}(name = "${t.name}")`, "starlark");
      const origin = !t.generated
        ? ""
        : t.generated.generatorFunction
          ? ` — generated by \`${t.generated.generatorFunction}\``
          : " — found by `bazel query`";
      md.appendMarkdown(`${shortLabel(t.pkg, t.name)}${origin}\n\n`);
    } else {
      md.appendMarkdown("Source file\n\n");
    }
    md.appendMarkdown(fileLink(first, ctx.index.root));
    return new vscode.Hover(
      md,
      new vscode.Range(
        document.positionAt(node.literal.start),
        document.positionAt(node.literal.end),
      ),
    );
  }
}

function definitionMarkdown(
  name: string,
  location: ResolvedLocation | undefined,
  schema: CallableSchema | undefined,
  root: string,
): vscode.MarkdownString {
  const def = location?.definition as BzlDefinition | undefined;
  const md = new vscode.MarkdownString();
  md.isTrusted = false;
  let signature: string;
  if (schema) {
    const attrs = offeredAttrs(schema).map((a) => a.name);
    const shown = attrs.slice(0, 8).join(", ");
    const more = attrs.length > 8 ? ", …" : "";
    const kwargs = schema.openEnded ? ", **kwargs" : "";
    signature = `${schema.kind === "macro" ? "def " : ""}${name}(${shown}${more}${kwargs})`;
  } else {
    signature =
      def?.kind === "function"
        ? `def ${name}(...)`
        : `${name} = ${def?.kind}(...)`;
  }
  md.appendCodeblock(signature, "starlark");
  const text = (schema?.doc ?? def?.doc)?.trim();
  if (text) {
    md.appendMarkdown(
      (text.length > MAX_DOC_LENGTH
        ? text.slice(0, MAX_DOC_LENGTH) + "…"
        : text) + "\n\n",
    );
  }
  if (location) {
    md.appendMarkdown(fileLink(location, root));
  } else if (schema?.file === "") {
    md.appendMarkdown("Built into Bazel");
  }
  return md;
}

function fileLink(location: ResolvedLocation, root: string): string {
  const fsPath = location.uri.fsPath;
  const rel = path.relative(root, fsPath);
  const display = rel.startsWith("..") || path.isAbsolute(rel) ? fsPath : rel;
  const line = location.range.start.line + 1;
  return `[${display}:${line}](${location.uri.with({
    fragment: `L${line}`,
  })})`;
}
